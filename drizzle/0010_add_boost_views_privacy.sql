-- Boost: a project can be pushed to the top of Explore until this time.
ALTER TABLE "kvelpo_project" ADD COLUMN IF NOT EXISTS "boostedUntil" timestamp with time zone;
CREATE INDEX IF NOT EXISTS "projects_boosted_until_idx" ON "kvelpo_project" ("boostedUntil");

-- Browse privately: owners see a skill-based placeholder instead of this person's name.
ALTER TABLE "kvelpo_profile" ADD COLUMN IF NOT EXISTS "browsePrivately" boolean DEFAULT false NOT NULL;

-- One row per signed-in viewer per project per day (owners' own views are not recorded).
CREATE TABLE IF NOT EXISTS "kvelpo_project_view" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "kvelpo_project_view_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"projectId" integer NOT NULL,
	"viewerClerkUserId" varchar(256) NOT NULL,
	"viewedOn" date NOT NULL,
	"isPrivate" boolean DEFAULT false NOT NULL,
	"viewerSkill" varchar(128),
	"createdAt" timestamp with time zone NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "project_view_unique_idx" ON "kvelpo_project_view" ("projectId", "viewerClerkUserId", "viewedOn");
CREATE INDEX IF NOT EXISTS "project_view_project_idx" ON "kvelpo_project_view" ("projectId", "viewedOn");
CREATE INDEX IF NOT EXISTS "project_view_viewer_idx" ON "kvelpo_project_view" ("viewerClerkUserId");
DO $$ BEGIN
  ALTER TABLE "kvelpo_project_view" ADD CONSTRAINT "kvelpo_project_view_projectId_fk" FOREIGN KEY ("projectId") REFERENCES "kvelpo_project"("id") ON DELETE CASCADE;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- Boost purchases: idempotency (one row per Stripe Checkout session) and history.
-- No foreign key on projectId so the record survives if the project is deleted.
CREATE TABLE IF NOT EXISTS "kvelpo_boost_purchase" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "kvelpo_boost_purchase_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"stripeSessionId" varchar(256) NOT NULL,
	"projectId" integer NOT NULL,
	"clerkUserId" varchar(256) NOT NULL,
	"amountTotal" integer,
	"currency" varchar(8),
	"boostedUntil" timestamp with time zone NOT NULL,
	"createdAt" timestamp with time zone NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "boost_purchase_session_idx" ON "kvelpo_boost_purchase" ("stripeSessionId");
CREATE INDEX IF NOT EXISTS "boost_purchase_user_idx" ON "kvelpo_boost_purchase" ("clerkUserId");
